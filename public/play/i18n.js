/* 目前語言:'zh'(繁中,原文) | 'en'。偵測順序:玩家設定(localStorage) → 平台語言 hook(window._platformLang,
 * CrazyGames 版 bootstrap 可在載入前設定) → navigator.language(zh*→zh,其餘→en)。 */
let _i18nLang = null;
function getLang() {
  if (_i18nLang) return _i18nLang;
  let saved = null; try { saved = localStorage.getItem('ninja_lang'); } catch (e) { }
  if (saved === 'zh' || saved === 'en') { _i18nLang = saved; return _i18nLang; }
  if (typeof window !== 'undefined' && (window._platformLang === 'zh' || window._platformLang === 'en')) { _i18nLang = window._platformLang; return _i18nLang; }
  const nav = ((typeof navigator !== 'undefined' && navigator.language) || 'zh').toLowerCase();
  _i18nLang = nav.indexOf('zh') === 0 ? 'zh' : 'en';
  return _i18nLang;
}
function setLang(l) { if (l !== 'zh' && l !== 'en') return; _i18nLang = l; try { localStorage.setItem('ninja_lang', l); } catch (e) { } }

/* tr(中文原文, params?) → 依語言回譯文;查無回原文;{k} 模板插值(中英都插)。 */
function tr(s, params) {
  let out = s;
  const lang = getLang();
  if (lang !== 'zh') { const d = I18N_DICT[lang]; if (d && d[s] != null) out = d[s]; }
  if (params) { for (const k in params) { out = out.split('{' + k + '}').join(params[k]); } }
  return out;
}

